// Expected values come from an independent reference, not from GEOS.
// NetTopologySuite has no clothoid, so the reference is mpmath at 50 digits,
// using the ISO/IEC 13249-3 and Koc (2025) definition
//   P(t) = origin + A C2(t/A) u + A S2(t/A) v,  C2(x) = int_0^x cos(tau^2/2).
// The table is generated outside the GEOS tree by gen_tests.py from the
// output of clothoid_oracle.py; there is no runtime dependency on either.
// Generated by geos-oracle/gen_tests.py from clothoid_oracle.py sha256 ac988d1039384e89...
//
// Tolerances: GEOS evaluates in double precision, so coordinates are checked
// to 1e-12 of the reference extent R = max|origin| + max(|u|, |v|) max(|t0|, |t1|).
// The worst case in the table is the 1024 rad limit, which misses by 5e-13 R.
// Lengths and curvatures are checked to 1e-12 relative, and headings to
// 1e-12 (1 + turn) because the heading grows with the turn.
struct OracleCase {
    const char* name;
    bool hasZ;
    bool checkCurvature;
    double origin[3];
    double u[3];
    double v[3];
    double scale;
    double t0;
    double t1;
    double start[3];
    double end[3];
    double length;
    double startHeading;
    double endHeading;
    double startCurvature;
    double endCurvature;
    double envelope[4];
    double stations[3][3];
};

