struct test_clothoidoracle_data {
    geos::geom::GeometryFactory::Ptr factory_ = geos::geom::GeometryFactory::create();

    static ClothoidReferenceLocation locationOf(const OracleCase& c)
    {
        return ClothoidReferenceLocation{
            Coordinate(c.origin[0], c.origin[1], c.origin[2]),
            Coordinate(c.u[0], c.u[1], c.u[2]),
            Coordinate(c.v[0], c.v[1], c.v[2])};
    }

    std::unique_ptr<Clothoid> build(const OracleCase& c, double t1) const
    {
        return factory_->createClothoid(locationOf(c), c.scale, c.t0, t1,
                                        c.hasZ, false,
                                        geos::DoubleNotANumber, geos::DoubleNotANumber);
    }

    static double extent(const OracleCase& c)
    {
        const double o = std::max({std::abs(c.origin[0]), std::abs(c.origin[1]), std::abs(c.origin[2])});
        const double u = std::sqrt(c.u[0] * c.u[0] + c.u[1] * c.u[1] + c.u[2] * c.u[2]);
        const double v = std::sqrt(c.v[0] * c.v[0] + c.v[1] * c.v[1] + c.v[2] * c.v[2]);
        return o + std::max(u, v) * std::max(std::abs(c.t0), std::abs(c.t1));
    }

    static double turn(const OracleCase& c)
    {
        return std::abs(c.t1 * c.t1 - c.t0 * c.t0) / (2.0 * c.scale * c.scale);
    }

    static void near(const std::string& what, double got, double expected, double tol)
    {
        ensure(what + ": got " + std::to_string(got) + " expected " + std::to_string(expected),
               std::abs(got - expected) <= tol);
    }

    static void nearRelative(const std::string& what, double got, double expected)
    {
        near(what, got, expected, 1e-12 * std::abs(expected));
    }
};

typedef test_group<test_clothoidoracle_data> group;
typedef group::object object;

group test_clothoidoracle_group("geos::geom::ClothoidOracle");

template<>
template<>
void object::test<1>()
{
    set_test_name("end points, length and headings");

    for (const auto& c : ORACLE_CASES) {
        const std::string name(c.name);
        auto curve = build(c, c.t1);
        const double tol = 1e-12 * extent(c);
        const auto& pts = *curve->getCoordinatesRO();
        const Coordinate s = pts.getAt<Coordinate>(0);
        const Coordinate e = pts.getAt<Coordinate>(1);
        near(name + " start x", s.x, c.start[0], tol);
        near(name + " start y", s.y, c.start[1], tol);
        near(name + " end x", e.x, c.end[0], tol);
        near(name + " end y", e.y, c.end[1], tol);
        if (c.hasZ) {
            near(name + " start z", s.z, c.start[2], tol);
            near(name + " end z", e.z, c.end[2], tol);
        }
        nearRelative(name + " length", curve->getLength(), c.length);
        const double htol = 1e-12 * (1.0 + turn(c));
        near(name + " start heading", curve->getStartHeading(), c.startHeading, htol);
        near(name + " end heading", curve->getEndHeading(), c.endHeading, htol);
    }
}

template<>
template<>
void object::test<2>()
{
    set_test_name("curvature at both ends");

    for (const auto& c : ORACLE_CASES) {
        if (!c.checkCurvature) {
            continue;
        }
        const std::string name(c.name);
        auto curve = build(c, c.t1);
        nearRelative(name + " start curvature", curve->getStartCurvature(), c.startCurvature);
        nearRelative(name + " end curvature", curve->getEndCurvature(), c.endCurvature);
    }
}

template<>
template<>
void object::test<3>()
{
    set_test_name("envelope");

    for (const auto& c : ORACLE_CASES) {
        const std::string name(c.name);
        auto curve = build(c, c.t1);
        const double tol = 1e-12 * extent(c);
        const auto* env = curve->getEnvelopeInternal();
        near(name + " min x", env->getMinX(), c.envelope[0], tol);
        near(name + " max x", env->getMaxX(), c.envelope[1], tol);
        near(name + " min y", env->getMinY(), c.envelope[2], tol);
        near(name + " max y", env->getMaxY(), c.envelope[3], tol);
    }
}

template<>
template<>
void object::test<4>()
{
    set_test_name("stations along the curve");

    // A clothoid ending at an intermediate distance shares the placement, so
    // its end point is the station on the full curve.
    for (const auto& c : ORACLE_CASES) {
        const std::string name(c.name);
        const double tol = 1e-12 * extent(c);
        for (const auto& station : c.stations) {
            const double t = c.t0 + (c.t1 - c.t0) * station[0];
            auto part = build(c, t);
            const auto e = part->getCoordinatesRO()->getAt<Coordinate>(1);
            const std::string at = name + " at " + std::to_string(station[0]);
            near(at + " x", e.x, station[1], tol);
            near(at + " y", e.y, station[2], tol);
        }
    }
}

template<>
template<>
void object::test<5>()
{
    set_test_name("reverse keeps the oracle geometry");

    for (const auto& c : ORACLE_CASES) {
        const std::string name(c.name);
        auto curve = build(c, c.t1);
        auto reversed = curve->reverse();
        const double tol = 1e-12 * extent(c);
        const auto& pts = *reversed->getCoordinatesRO();
        near(name + " reversed start x", pts.getAt<Coordinate>(0).x, c.end[0], tol);
        near(name + " reversed start y", pts.getAt<Coordinate>(0).y, c.end[1], tol);
        near(name + " reversed end x", pts.getAt<Coordinate>(1).x, c.start[0], tol);
        near(name + " reversed end y", pts.getAt<Coordinate>(1).y, c.start[1], tol);
        nearRelative(name + " reversed length", reversed->getLength(), c.length);
        if (c.checkCurvature) {
            nearRelative(name + " reversed start curvature",
                         reversed->getStartCurvature(), -c.endCurvature);
        }
        // A zero tangent has no heading to reverse.
        if (c.t0 == 0.0 && std::hypot(c.u[0], c.u[1]) == 0.0) {
            continue;
        }
        const double htol = 1e-12 * (1.0 + turn(c));
        const double back = std::remainder(reversed->getEndHeading() - (c.startHeading + geos::MATH_PI),
                                           2.0 * geos::MATH_PI);
        near(name + " reversed end heading", back, 0.0, htol);
    }
}

template<>
template<>
void object::test<6>()
{
    set_test_name("WKT and WKB round trips");

    geos::io::WKTWriter wktWriter;
    wktWriter.setRoundingPrecision(17);
    wktWriter.setOutputDimension(3);
    geos::io::WKTReader wktReader(*factory_);
    geos::io::WKBWriter wkbWriter;
    wkbWriter.setOutputDimension(3);
    geos::io::WKBReader wkbReader(*factory_);

    for (const auto& c : ORACLE_CASES) {
        const std::string name(c.name);
        auto curve = build(c, c.t1);
        auto fromWkt = wktReader.read<Clothoid>(wktWriter.write(curve.get()));
        ensure(name + " WKT", curve->equalsIdentical(fromWkt.get()));

        std::stringstream wkb;
        wkbWriter.write(*curve, wkb);
        auto fromWkb = wkbReader.read(wkb);
        ensure(name + " WKB", curve->equalsIdentical(fromWkb.get()));
    }
}

